import fs from 'node:fs'
import { journey, login, expect, modal, emptySelects, logMark, logSince, tinker, STATE } from './lib.mjs'
const { competitionId } = JSON.parse(fs.readFileSync(STATE))
const mailsTo = text => [...text.matchAll(/To: [^\n]*?([\w.+-]+@beerjudge\.local)/g)].map(m => m[1])

await journey('A5-close-and-publish', async actor => {
  const { page, step } = await actor('member2-admin')
  await login(page, 'member2@beerjudge.local')
  await step('results tab flags the high-spread entry', async () => {
    await page.goto(`/admin/competitions/${competitionId}/edit`)
    await page.waitForLoadState('networkidle')
    await page.getByRole('tab', { name: 'Results & Variance' }).click()
    await page.waitForTimeout(1000)
    const t = await page.locator('[role=tabpanel]:visible').innerText()
    console.log('  variance panel:', t.replace(/\s+/g, ' ').slice(0, 300))
    if (!/29/.test(t)) throw new Error('spread 29 not shown')
  })
  await step('move to closed asks for confirmation', async () => {
    globalThis.mark = logMark()
    await page.getByRole('button', { name: 'Move to Closed' }).click()
    await expect(modal(page).getByRole('button', { name: /Confirm/ })).toBeVisible({ timeout: 10000 })
  })
  await step('confirm closes and mails each participant once', async () => {
    await modal(page).getByRole('button', { name: /Confirm/ }).click()
    await page.waitForLoadState('networkidle')
    await page.waitForTimeout(1500)
    const to = mailsTo(logSince(globalThis.mark))
    console.log('  results mail to:', to.join(','))
    const expected = ['member3', 'member4', 'member5', 'member6', 'member7'].map(m => m + '@beerjudge.local')
    for (const e of expected) if (to.filter(x => x === e).length !== 1) throw new Error('mail count for ' + e)
    if (tinker(`echo App\\Models\\Competition::find(${competitionId})->results_mailed_at ? "set" : "null";`) !== 'set') throw new Error('results_mailed_at not set')
  })
  await step('header after reload: view results, resend, reopen', async () => {
    await page.reload()
    await expect(page.getByRole('link', { name: 'View Results' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Resend results email' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Reopen judging' })).toBeVisible()
  })
  await step('results index lists participants and judges for admin', async () => {
    await page.goto(`/competitions/${competitionId}/results`)
    await expect(page.locator('body')).toContainText('Member Seven')
    await expect(page.locator('body')).toContainText('Member 3')
  })
  await step('resend results to member5 only', async () => {
    await page.goto(`/admin/competitions/${competitionId}/edit`)
    await page.waitForLoadState('networkidle')
    globalThis.mark = logMark()
    await page.getByRole('button', { name: 'Resend results email' }).click()
    const d = modal(page)
    await emptySelects(d).click()
    await page.getByRole('option', { name: 'Member 5' }).first().click()
    await page.waitForTimeout(400)
    console.log('  resend modal buttons:', (await d.getByRole('button').allInnerTexts()).filter(Boolean).join(' | '))
    await d.getByRole('button', { name: /Submit|Send|Confirm|Resend/ }).last().click()
    await expect(page.getByText('Results email sent').first()).toBeVisible()
    const to = mailsTo(logSince(globalThis.mark))
    console.log('  resend mail to:', to.join(','))
    if (to.join() !== 'member5@beerjudge.local') throw new Error('resend went to ' + to)
  })
})
